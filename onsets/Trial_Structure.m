%% Experiment Descriptive Stats

clear;
clc;

%% Load Data
% Load subject data file
[file, path] = uigetfile('*.mat', 'Trial Spike Data File');

raw = load(fullfile(path, file));
varName = fieldnames(raw);
ts = raw.(varName{1});

[unitFile, unitPath] = uigetfile('*.mat', 'Unit Table');

unitRaw = load(fullfile(unitPath, unitFile));
unitvarName = fieldnames(unitRaw);
T = unitRaw.(unitvarName{1});

uniqueMice = unique(T.mouseNum);
allTables = cell(numel(uniqueMice), 1);
lightState = cell(numel(uniqueMice), 1);

maxBlocks = 0;
maxDarkBlocks = 0;

for m = 1:numel(uniqueMice)
    thisMouse = uniqueMice(m);
    lit_tmp = ts(thisMouse).T.isDarkTrial(:) == 0;
    padded_tmp = [0, lit_tmp', 0];
    n_blocks = sum(diff(padded_tmp) == 1);   % number of 0→1 transitions = number of blocks
    maxBlocks = max(maxBlocks, n_blocks);

    dark_tmp = ts(thisMouse).T.isDarkTrial(:) == 1;
    padded_dark_tmp = [0, dark_tmp', 0];
    n_dark_blocks = sum(diff(padded_dark_tmp) == 1);
    maxDarkBlocks = max(maxDarkBlocks, n_dark_blocks);
end

for m = 1:numel(uniqueMice) % Loop over all mouse tables
    thisMouse = uniqueMice(m);
    mouseID = unique(T.mouseID(T.mouseNum == thisMouse, :));
    subjectData = ts(thisMouse).T;

    nTrials = height(subjectData);
    
    rest_dur = subjectData.stayDurs(:);
    speed = subjectData.speeds(:);
    slow = subjectData.speeds == 1;
    lit = subjectData.isDarkTrial(:) == 0;

    base = subjectData.phase(:) == 1;
    main = subjectData.phase(:) == 2;
    test = subjectData.phase(:) == 3;

    far_base = subjectData.isFar(base) == 1;
    far_main = subjectData.isFar(main) == 1;
    far_test = subjectData.isFar(test) == 1;

    left = subjectData.sideIdx(:) == 2;

    min_rest_dur = min(rest_dur);
    max_rest_dur = max(rest_dur);
    
    fast_app_dur = subjectData.Toff(speed(:) == 2) - subjectData.Ton(speed(:) == 2);
    fast_rec_dur = subjectData.Toff_rec(speed(:) == 2) - subjectData.Ton_rec(speed(:) == 2);

    slow_app_dur = subjectData.Toff(speed(:) == 1) - subjectData.Ton(speed(:) == 1);
    slow_rec_dur = subjectData.Toff_rec(speed(:) == 1) - subjectData.Ton_rec(speed(:) == 1);

    padded_lit = [0, lit', 0];
    starts_lit = (find(diff(padded_lit) == 1)) - 1;
    ends_lit = (find(diff(padded_lit) == -1)) - 1;

    lengths_lit = ends_lit - starts_lit;

    padded_dark = [0, ~lit', 0];
    starts_dark = (find(diff(padded_dark) == 1)) - 1;
    ends_dark   = (find(diff(padded_dark) == -1)) - 1;

    lengths_dark = ends_dark - starts_dark;


    allTables{m} = table( ...
        mouseID, ...
        nTrials, ...
        sum(lit), ...
        nTrials - sum(lit), ...
        sum(lit)/nTrials, ...
        sum(base), ...
        sum(far_base), ...
        sum(main), ...
        sum(far_main), ...
        sum(test), ...
        sum(far_test), ...
        (sum(left)/nTrials), ...
        (sum(slow)/nTrials), ...
        mean((fast_app_dur + fast_rec_dur)/2), ...
        mean((slow_app_dur + slow_rec_dur)/2), ...
        mean(rest_dur), ...
        std(rest_dur), ...
        min(rest_dur), ...
        max(rest_dur), ...
        'VariableNames', {...
        'mouseID', ...
        'nTrials', ...
        'nLit', ...
        'nDark', ...
        'Pr_Lit', ...
        'nBase', ...
        'nFarBase', ...
        'nMain', ...
        'nFarMain', ...
        'nTest', ...
        'nFarTest', ...
        'Pr_Left', ...
        'Pr_Slow', ...
        'dur_Fast', ...
        'dur_Slow', ...
        'mean_Rest', ...
        'stdev_Rest', ...
        'min_Rest', ...
        'max_Rest' ...
        });


    Blocks = maxBlocks;

    starts_pad = nan(1, Blocks);
    ends_pad = nan(1, Blocks);
    lengths_pad = nan(1, Blocks);

    n = numel(lengths_lit);
    starts_pad(1:n)  = starts_lit;
    ends_pad(1:n)    = ends_lit;
    lengths_pad(1:n) = lengths_lit;

    starts_dark_pad  = nan(1, maxDarkBlocks);
    ends_dark_pad    = nan(1, maxDarkBlocks);
    lengths_dark_pad = nan(1, maxDarkBlocks);

    nd = numel(lengths_dark);
    starts_dark_pad(1:nd)  = starts_dark;
    ends_dark_pad(1:nd)    = ends_dark;
    lengths_dark_pad(1:nd) = lengths_dark;

    lightState{m} = table( ...
        mouseID, ...
        nTrials, ...
        starts_pad, ...
        ends_pad, ...
        lengths_pad, ...
        lengths_dark_pad, ...
        'VariableNames', {...
        'mouseID', ...
        'nTrials', ...
        'startLit', ...
        'endLit', ...
        'blockLen', ...
        'darkBlockLen' ...
        });
end

summaryTable = vertcat(allTables{:});

[saveFile, savePath] = uiputfile('*.mat', 'Save results table', 'Exp_Overview.mat');
if ~isequal(saveFile, 0)
    save(fullfile(savePath, saveFile), 'summaryTable');
end

summaryLight = vertcat(lightState{:});

[saveFile, savePath] = uiputfile('*.mat', 'Save results table', 'Light_Overview.mat');
if ~isequal(saveFile, 0)
    save(fullfile(savePath, saveFile), 'summaryLight');
end
